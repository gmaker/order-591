/** Horizontal/vertical offset of the 5×7 glyph inside its 8×8 cell. */
export const FONT_X_OFFSET = 1;
export const FONT_Y_OFFSET = 0;

/**
 * Rows for a character, falling back to '?' for anything unknown.
 * @param {string} ch single character
 */
export function fontRows(ch) {
  return FONT[ch.toUpperCase()] ?? FONT['?'];
}
